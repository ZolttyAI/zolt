def test_mix_datasets_ratio():
    corpus = [{"content": f"code_{i}", "lang": "python", "license": "mit"} for i in range(80)]
    distilled = [
        {"content": f"distill_{i}", "lang": "python", "license": "synthetic"} for i in range(20)
    ]

    with tempfile.NamedTemporaryFile(mode="w", suffix=".jsonl", delete=False) as fc:
        for r in corpus:
            fc.write(json.dumps(r) + "\n")
        c_path = fc.name

    with tempfile.NamedTemporaryFile(mode="w", suffix=".jsonl", delete=False) as fd:
        for r in distilled:
            fd.write(json.dumps(r) + "\n")
        d_path = fd.name

    with tempfile.NamedTemporaryFile(mode="w", suffix=".jsonl", delete=False) as fout:
        out_path = fout.name

    stats = mix_datasets([c_path], [d_path], out_path, distill_ratio=0.20)
    assert stats["total"] > 0
    assert 0.15 <= stats["actual_distill_ratio"] <= 0.25

    os.unlink(c_path)
    os.unlink(d_path)
    os.unlink(out_path)


# --- Curriculum Learning Tests ---


def test_curriculum_complexity_scoring():
    simple_code = "x = 1"
    complex_code = (
        "class Router:\n"
        "    def route(self, req):\n"
        "        for pattern in self.routes:\n"
        "            if pattern.matches(req):\n"
        "                try:\n"
        "                    return self.dispatch(pattern, req)\n"
        "                except Exception as e:\n"
        "                    pass\n"
    )
    score_simple = estimate_code_complexity(simple_code)
    score_complex = estimate_code_complexity(complex_code)
    assert score_complex > score_simple

    ordered = sort_by_curriculum([complex_code, simple_code])
    assert ordered[0] == simple_code
    assert ordered[1] == complex_code


def test_packed_dataset_curriculum_ordering():
    simple_seq = {"input_ids": [10, 11, 12]}
    complex_seq = {"input_ids": list(range(100, 200))}

    with tempfile.NamedTemporaryFile(mode="w", suffix=".jsonl", delete=False) as f:
        f.write(json.dumps(complex_seq) + "\n")
        f.write(json.dumps(simple_seq) + "\n")
        f_path = f.name

    ds = PackedSequenceDataset([f_path], max_seq_len=64, curriculum=True, shuffle=False)
    docs = ds._load_documents(f_path)
    sorted_docs = sort_by_curriculum(docs, complexity_fn=estimate_token_sequence_complexity)
    assert len(sorted_docs[0]) < len(sorted_docs[1])

    os.unlink(f_path)


# --- PackedSequenceDataset Tests ---


def test_packed_dataset_basic():
    """Verify that PackedSequenceDataset produces properly shaped batches."""
    import tempfile

    import numpy as np

    tokens = list(range(1, 5001))  # 5000 sequential tokens
    arr = np.array(tokens, dtype=np.int32)

    with tempfile.NamedTemporaryFile(suffix=".bin", delete=False) as f:
        arr.tofile(f)
        bin_path = f.name

    dataset = PackedSequenceDataset(
        token_files=[bin_path],
        max_seq_len=128,
        bos_id=1,
        eos_id=2,
        pad_id=0,
        shuffle=False,
    )

    batches = list(dataset)
    assert len(batches) > 0

    for batch in batches:
        assert "input_ids" in batch
        assert "labels" in batch
        assert batch["input_ids"].shape[0] == 128
        assert batch["labels"].shape[0] == 128

    os.unlink(bin_path)
