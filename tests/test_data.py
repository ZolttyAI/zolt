def test_filter_jsonl_file():
    records = [
        {"content": "def foo():\n    return 42\n" * 10, "lang": "python", "license": "mit"},
        {
            "content": "import java.util.List;",
            "lang": "java",
            "license": "mit",
        },  # reject: wrong lang
        {
            "content": "const x = 1;",
            "lang": "javascript",
            "license": "GPL-3.0",
        },  # reject: non-permissive license
        {"content": "   ", "lang": "python", "license": "mit"},  # reject: quality heuristic
        {
            "content": "def foo():\n    return 42\n" * 10,
            "lang": "python",
            "license": "mit",
        },  # reject: duplicate content
    ]

    with tempfile.NamedTemporaryFile(mode="w", suffix=".jsonl", delete=False) as fin:
        for r in records:
            fin.write(json.dumps(r) + "\n")
        input_path = fin.name

    with tempfile.NamedTemporaryFile(mode="w", suffix=".jsonl", delete=False) as fout:
        output_path = fout.name

    stats = filter_jsonl_file(input_path, output_path)

    assert stats["accepted"] == 1
    assert stats["lang_filtered"] == 1
    assert stats["license_filtered"] == 1
    assert stats["dedup_filtered"] == 1

    os.unlink(input_path)
    os.unlink(output_path)


# --- Textbook Quality Score Heuristic Tests ---


def test_score_comments_and_docstrings():
    well_documented = (
        '"""Module for calculation."""\n'
        "# Helper function for addition\n"
        "def add(a: int, b: int) -> int:\n"
        '    """Return sum of two integers."""\n'
        "    return a + b\n"
    )
    undocumented = "def add(a, b):\n    return a + b\n" * 10
    score_high = score_comments_and_docstrings(well_documented, "python")
    score_low = score_comments_and_docstrings(undocumented, "python")
    assert score_high > score_low


def test_score_test_presence():
    assert score_test_presence("tests/test_service.py", "") == 1.0
    assert score_test_presence("src/service.spec.ts", "") == 1.0
    assert score_test_presence("src/service.py", "import pytest\ndef test_fn(): pass") == 0.85
    assert score_test_presence("src/service.py", "def fn(): pass") == 0.5


def test_score_anti_patterns():
    clean_code = "function solve() {\n  return 42;\n}\n"
    generated_code = "// @generated by protobuf\nconst x = 1;"
    minified_code = "const " + "a" * 700 + "=1;"
    assert score_anti_patterns(clean_code, "src/index.js") == 1.0
    assert score_anti_patterns(generated_code, "src/proto.js") == 0.0
    assert score_anti_patterns(minified_code, "src/bundle.js") == 0.0
    assert score_anti_patterns(clean_code, "node_modules/pkg/index.js") == 0.0


def test_score_complexity_readability():
    clean_structured = (
        "def process(items):\n    for x in items:\n        if x > 0:\n            yield x * 2\n"
    )
    score = score_complexity_readability(clean_structured, "python")
    assert 0.5 <= score <= 1.0


